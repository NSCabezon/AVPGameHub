#!/usr/bin/env python3
"""Generate runtime/guest/kl_openvr_vtables.h from OpenVR's public openvr.h.

    python3 tools/gen_openvr_vtables.py <openvr>/headers/openvr.h > runtime/guest/kl_openvr_vtables.h

ValveSoftware/openvr (BSD-3). kl_openvr.c hands the guest C++ interface objects
in place of libopenvr_api.so's, so it needs each interface's vtable order, which
the header states: one slot per virtual in declaration order (Itanium ABI, as
GCC lays it out on Linux), two for a virtual destructor. The version string per
class comes from its `I<Name>_Version` constant.
"""
import re, sys

def strip(s):
    s = re.sub(r'/\*.*?\*/', '', s, flags=re.S)
    return re.sub(r'//[^\n]*', '', s)

def main(path):
    src = strip(open(path, errors='ignore').read())
    vers = dict(re.findall(r'static\s+const\s+char\s*\*\s*const\s+(\w+)_Version\s*=\s*"(\w+)"', src))
    print('// GENERATED by tools/gen_openvr_vtables.py from OpenVR\'s openvr.h (BSD-3) —')
    print('// do not edit. Each row: interface version string, class, then its vtable')
    print('// slots in order. Read by kl_openvr.c.')
    print('#ifndef KL_OVR_IFACE')
    print('#error "include through kl_openvr.c"')
    print('#endif')
    for cls, ver in vers.items():
        m = re.search(r'class\s+' + cls + r'\s*\{', src)
        if not m:
            continue
        depth, i = 1, m.end()          # the body, by brace matching
        while depth and i < len(src):
            depth += {'{': 1, '}': -1}.get(src[i], 0)
            i += 1
        body = src[m.end():i - 1]
        slots = []
        for mm in re.finditer(r'\bvirtual\s+([^;(]*?)\b(~?\w+)\s*\(', body):
            n = mm.group(2)
            slots += [n + '_complete', n + '_deleting'] if n.startswith('~') else [n]
        if slots:
            print('KL_OVR_IFACE("%s", "%s", %s)' % (ver, cls, ', '.join('"%s"' % s for s in slots)))

if __name__ == '__main__':
    main(sys.argv[1])
