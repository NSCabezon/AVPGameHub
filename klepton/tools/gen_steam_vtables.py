#!/usr/bin/env python3
"""Generate runtime/guest/kl_steam_vtables.h from a Steamworks SDK.

    python3 tools/gen_steam_vtables.py <sdk>/public/steam > runtime/guest/kl_steam_vtables.h

    # ...and to ADD an older SDK's interface versions to an existing table:
    python3 tools/gen_steam_vtables.py --extend runtime/guest/kl_steam_vtables.h \
        <older-sdk>/public/steam > /tmp/t.h && mv /tmp/t.h runtime/guest/kl_steam_vtables.h

--extend exists because a guest asks for interfaces BY VERSION STRING, and two
guests built against different SDKs ask for different strings. Half-Life:
Alyx is built against a 2025 SDK (SteamUtils011, SteamFriends018, ...); Metro
Awakening's Android build against SDK 1.60 (SteamUtils010, SteamFriends017,
STEAMAPPS_INTERFACE_VERSION008, ...). A version the table does not describe gets
128 logging stubs, which is fine for an interface nobody calls and fatal for
ISteamUtils. So the existing file is kept byte for byte and only rows for
versions it does not already have are appended — a version string names one
vtable layout forever, so the first SDK to describe it is as good as any.

    # ...and the FLAT API table (Steamworks.NET calls SteamAPI_ISteamX_Method):
    python3 tools/gen_steam_vtables.py --flat <newest-sdk> <older-sdk>... \
        > runtime/guest/kl_steam_flat.h

The Steam stub (kl_steam.c) hands the guest C++ interface objects, so it needs
each interface's VTABLE ORDER, which only the headers state exactly:
steam_api.json lists the flat API (it includes inline non-virtual helpers and
omits the STEAM_PRIVATE_API slots), so the headers are parsed and the json
only supplies which classes exist and their version strings. Itanium ABI
(GCC, Linux arm64): one slot per virtual in declaration order, overloads
included, and two slots for a virtual destructor.
"""
import glob, json, os, re, sys

def strip(s):
    s = re.sub(r'/\*.*?\*/', '', s, flags=re.S)
    return re.sub(r'//[^\n]*', '', s)

def rows(d):
    """(version, line) for every interface the SDK at `d` describes."""
    src = strip(''.join(open(f, errors='ignore').read()
                        for f in sorted(glob.glob(os.path.join(d, '*.h')))))
    j = json.load(open(os.path.join(d, 'steam_api.json')))
    for i in j['interfaces']:
        c, ver = i['classname'], i.get('version_string')
        if c == 'ISteamClient':   # the json names no version for it; isteamclient.h does
            mv = re.search(r'STEAMCLIENT_INTERFACE_VERSION\s+"(\w+)"', src)
            ver = mv.group(1) if mv else None
        if not ver:
            continue
        m = re.search(r'class\s+' + c + r'\b[^;{]*\{(.*?)\n\};', src, re.S)
        if not m:
            continue
        slots = []
        for mm in re.finditer(r'\bvirtual\s+([^;(]*?)\b(~?\w+)\s*\(', m.group(1)):
            name = mm.group(2)
            if name.startswith('~'):
                slots += [name + '_complete', name + '_deleting']
            else:
                slots.append(name)
        yield ver, 'KL_STEAM_IFACE("%s", "%s", %s)' % (ver, c, ', '.join('"%s"' % s for s in slots))

def flat_rows(d):
    """The FLAT API, as rows: every `SteamAPI_ISteamX_Method` names a class, a
    vtable method and which overload of it (GetStat has two slots and two flat
    names, GetStatInt32 / GetStatFloat), and every accessor
    (`SteamAPI_SteamUser_v023`) names the interface version it returns."""
    j = json.load(open(os.path.join(d, 'steam_api.json')))
    for i in j['interfaces']:
        c, seen = i['classname'], {}
        for m in i.get('methods', []):
            n = m['methodname']
            nth = seen.get(n, 0)
            seen[n] = nth + 1
            yield m['methodname_flat'], 'KL_STEAM_FLAT("%s", "%s", "%s", %d)' % (
                m['methodname_flat'], c, n, nth)
        ver = i.get('version_string')
        for a in i.get('accessors', []):
            if ver:
                yield a['name_flat'], 'KL_STEAM_ACCESSOR("%s", "%s")' % (a['name_flat'], ver)

def main(argv):
    if argv[0] == '--flat':
        # python3 tools/gen_steam_vtables.py --flat <sdk>... > runtime/guest/kl_steam_flat.h
        # Union over the SDKs given, first one wins per flat name.
        print('// GENERATED by tools/gen_steam_vtables.py --flat from the Steamworks SDK')
        print('// steam_api.json — do not edit. The flat API (Steamworks.NET, i.e. every')
        print('// Unity title) mapped onto the vtables in kl_steam_vtables.h. Read by kl_steam.c.')
        print('#if !defined(KL_STEAM_FLAT) || !defined(KL_STEAM_ACCESSOR)')
        print('#error "include through kl_steam.c"')
        print('#endif')
        have = set()
        for d in argv[1:]:
            for name, line in flat_rows(d):
                if name not in have:
                    have.add(name)
                    print(line)
        return
    if argv[0] == '--extend':
        existing = open(argv[1]).read()
        have = set(re.findall(r'^KL_STEAM_IFACE\("([^"]+)"', existing, re.M))
        sys.stdout.write(existing)
        for d in argv[2:]:
            for ver, line in rows(d):
                if ver not in have:
                    have.add(ver)
                    print(line)
        return
    print('// GENERATED by tools/gen_steam_vtables.py from the Steamworks SDK headers —')
    print('// do not edit. Each row: interface version string, then its vtable slots in')
    print('// order. Read by kl_steam.c.')
    print('#ifndef KL_STEAM_IFACE')
    print('#error "include through kl_steam.c"')
    print('#endif')
    for d in argv:
        for ver, line in rows(d):
            print(line)

if __name__ == '__main__':
    main(sys.argv[1:])
